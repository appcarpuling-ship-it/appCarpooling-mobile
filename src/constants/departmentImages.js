// Convierte clave de archivo a nombre para mostrar: 'san_martin' → 'San Martin'
export function formatDeptName(key) {
  return key.split('_').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}

// Retorna los departamentos de una provincia como array de { key, label, image }
export function getDepartmentsForProvince(province) {
  const depts = DEPARTMENT_IMAGES[province];
  if (!depts) return [];
  return Object.keys(depts).map(key => ({
    key,
    label: formatDeptName(key),
    image: depts[key],
  }));
}
